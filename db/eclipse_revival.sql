-- tipo_dano: Elementos o tipos de daño de armas y enemigos (Físico, Fuego, Hielo, Rayo, Veneno).
CREATE TABLE tipo_dano (
  id_tipo_dano INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(30) NOT NULL UNIQUE,
  color CHAR(7) NOT NULL,
  efecto_estado VARCHAR(20),
  PRIMARY KEY (id_tipo_dano)
);

-- combo_elemental: Combos que se activan cuando ataques de dos elementos de distintos jugadores golpean al mismo enemigo (relación N:M de tipo_dano consigo mismo).
CREATE TABLE combo_elemental (
  id_combo INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  id_tipo_dano_a INT NOT NULL,
  id_tipo_dano_b INT NOT NULL,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  multiplicador NUMERIC(4,2) NOT NULL,
  radio SMALLINT NOT NULL,
  PRIMARY KEY (id_combo),
  CONSTRAINT fk_combo_elemental_id_tipo_dano_a FOREIGN KEY (id_tipo_dano_a) REFERENCES tipo_dano(id_tipo_dano) ON DELETE CASCADE,
  CONSTRAINT fk_combo_elemental_id_tipo_dano_b FOREIGN KEY (id_tipo_dano_b) REFERENCES tipo_dano(id_tipo_dano) ON DELETE CASCADE,
  CHECK (id_tipo_dano_a <> id_tipo_dano_b),
  UNIQUE (id_tipo_dano_a, id_tipo_dano_b),
  CHECK (multiplicador > 0)
);

-- pasiva: Mejoras pasivas que se eligen al subir de nivel durante la partida.
CREATE TABLE pasiva (
  id_pasiva INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  atributo VARCHAR(20) NOT NULL,
  valor_nivel NUMERIC(6,2) NOT NULL,
  nivel_max SMALLINT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_pasiva),
  CHECK (nivel_max >= 1)
);

-- arma: Armas que atacan automáticamente. Una arma base puede evolucionar a otra arma cuando llega a su nivel máximo y el jugador tiene la pasiva requerida.
CREATE TABLE arma (
  id_arma INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  id_tipo_dano INT NOT NULL,
  patron VARCHAR(15) NOT NULL,
  dano_base NUMERIC(6,2) NOT NULL,
  cadencia NUMERIC(5,2) NOT NULL,
  alcance NUMERIC(6,2) NOT NULL,
  prob_critico NUMERIC(4,3) NOT NULL,
  nivel_max SMALLINT NOT NULL,
  bono_nivel NUMERIC(4,2) NOT NULL,
  es_evolucion BOOLEAN NOT NULL DEFAULT FALSE,
  id_arma_evolucion INT,
  id_pasiva_requerida INT,
  nivel_cuenta_req SMALLINT NOT NULL DEFAULT 1,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_arma),
  CONSTRAINT fk_arma_id_tipo_dano FOREIGN KEY (id_tipo_dano) REFERENCES tipo_dano(id_tipo_dano) ON DELETE RESTRICT,
  CONSTRAINT fk_arma_id_arma_evolucion FOREIGN KEY (id_arma_evolucion) REFERENCES arma(id_arma) ON DELETE SET NULL,
  CONSTRAINT fk_arma_id_pasiva_requerida FOREIGN KEY (id_pasiva_requerida) REFERENCES pasiva(id_pasiva) ON DELETE RESTRICT,
  CHECK (patron IN ('proyectil','orbita','aura','area','rayo')),
  CHECK (prob_critico BETWEEN 0 AND 1),
  CHECK (id_arma_evolucion IS NULL OR id_arma_evolucion <> id_arma),
  CHECK (nivel_max >= 1)
);

-- personaje: Personajes jugables con sus estadísticas base.
CREATE TABLE personaje (
  id_personaje INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  vida_base INT NOT NULL,
  velocidad NUMERIC(6,2) NOT NULL,
  habilidad VARCHAR(150) NOT NULL,
  nivel_cuenta_req SMALLINT NOT NULL DEFAULT 1,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_personaje)
);

-- tipo_enemigo: Tipos de enemigos, élites y jefes con sus valores base antes del escalado.
CREATE TABLE tipo_enemigo (
  id_tipo_enemigo INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  comportamiento VARCHAR(20) NOT NULL,
  id_tipo_dano INT NOT NULL,
  vida_base INT NOT NULL,
  dano_base NUMERIC(6,2) NOT NULL,
  velocidad NUMERIC(6,2) NOT NULL,
  armadura NUMERIC(5,2) NOT NULL,
  xp_otorgada INT NOT NULL,
  es_jefe BOOLEAN NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_tipo_enemigo),
  CONSTRAINT fk_tipo_enemigo_id_tipo_dano FOREIGN KEY (id_tipo_dano) REFERENCES tipo_dano(id_tipo_dano) ON DELETE RESTRICT,
  CHECK (comportamiento IN ('perseguir','distancia','explotar','embestir','invocar','jefe')),
  CHECK (vida_base > 0)
);

-- resistencia: Multiplicador de daño que recibe cada tipo de enemigo según el elemento (relación N:M).
CREATE TABLE resistencia (
  id_tipo_enemigo INT NOT NULL,
  id_tipo_dano INT NOT NULL,
  multiplicador NUMERIC(4,2) NOT NULL,
  PRIMARY KEY (id_tipo_enemigo, id_tipo_dano),
  CONSTRAINT fk_resistencia_id_tipo_dano FOREIGN KEY (id_tipo_dano) REFERENCES tipo_dano(id_tipo_dano) ON DELETE CASCADE,
  CONSTRAINT fk_resistencia_id_tipo_enemigo FOREIGN KEY (id_tipo_enemigo) REFERENCES tipo_enemigo(id_tipo_enemigo) ON DELETE CASCADE,
  CHECK (multiplicador >= 0)
);

-- objeto: Objetos que sueltan los enemigos durante la partida.
CREATE TABLE objeto (
  id_objeto INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  efecto VARCHAR(20) NOT NULL,
  valor NUMERIC(8,2) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_objeto),
  CHECK (efecto IN ('oro','curar','atraer_gemas','explotar','cofre'))
);

-- botin_enemigo: Objetos que puede soltar cada tipo de enemigo y su probabilidad (relación N:M).
CREATE TABLE botin_enemigo (
  id_tipo_enemigo INT NOT NULL,
  id_objeto INT NOT NULL,
  probabilidad NUMERIC(4,3) NOT NULL,
  PRIMARY KEY (id_tipo_enemigo, id_objeto),
  CONSTRAINT fk_botin_enemigo_id_tipo_enemigo FOREIGN KEY (id_tipo_enemigo) REFERENCES tipo_enemigo(id_tipo_enemigo) ON DELETE CASCADE,
  CONSTRAINT fk_botin_enemigo_id_objeto FOREIGN KEY (id_objeto) REFERENCES objeto(id_objeto) ON DELETE CASCADE,
  CHECK (probabilidad BETWEEN 0 AND 1)
);

-- mapa: Mapas o regiones donde se juega, en orden de desbloqueo.
CREATE TABLE mapa (
  id_mapa INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  descripcion VARCHAR(200) NOT NULL,
  peligro VARCHAR(30),
  orden_desbloqueo SMALLINT NOT NULL UNIQUE,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_mapa)
);

-- enemigo_mapa: Qué enemigos aparecen en cada mapa y en qué rondas; incluye jefes y jefe final (relación N:M).
CREATE TABLE enemigo_mapa (
  id_mapa INT NOT NULL,
  id_tipo_enemigo INT NOT NULL,
  ronda_desde SMALLINT NOT NULL,
  ronda_hasta SMALLINT,
  peso SMALLINT NOT NULL DEFAULT 1,
  rol VARCHAR(12) NOT NULL DEFAULT 'normal',
  PRIMARY KEY (id_mapa, id_tipo_enemigo),
  CONSTRAINT fk_enemigo_mapa_id_tipo_enemigo FOREIGN KEY (id_tipo_enemigo) REFERENCES tipo_enemigo(id_tipo_enemigo) ON DELETE CASCADE,
  CONSTRAINT fk_enemigo_mapa_id_mapa FOREIGN KEY (id_mapa) REFERENCES mapa(id_mapa) ON DELETE CASCADE,
  CHECK (rol IN ('normal','jefe','jefe_final')),
  CHECK (ronda_hasta IS NULL OR ronda_hasta >= ronda_desde),
  CHECK (peso > 0)
);

-- dificultad: Modos de dificultad: Fácil, Normal y Difícil.
CREATE TABLE dificultad (
  id_dificultad INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(15) NOT NULL UNIQUE,
  num_rondas SMALLINT NOT NULL,
  mult_cantidad NUMERIC(4,2) NOT NULL,
  mult_vida NUMERIC(4,2) NOT NULL,
  mult_dano NUMERIC(4,2) NOT NULL,
  mult_recompensa NUMERIC(4,2) NOT NULL,
  PRIMARY KEY (id_dificultad),
  CHECK (num_rondas > 0)
);

-- evento_especial: Eventos especiales que se sortean cada 3 o 4 rondas.
CREATE TABLE evento_especial (
  id_evento INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  objetivo VARCHAR(200) NOT NULL,
  recompensa_oro INT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (id_evento)
);

-- mejora_permanente: Mejoras del taller que el jugador compra con oro entre partidas.
CREATE TABLE mejora_permanente (
  id_mejora INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre VARCHAR(40) NOT NULL UNIQUE,
  atributo VARCHAR(20) NOT NULL,
  valor_nivel NUMERIC(6,2) NOT NULL,
  nivel_max SMALLINT NOT NULL,
  costo_base INT NOT NULL,
  incremento_costo NUMERIC(4,2) NOT NULL,
  nivel_cuenta_req SMALLINT NOT NULL DEFAULT 1,
  PRIMARY KEY (id_mejora),
  CHECK (nivel_max >= 1),
  CHECK (costo_base > 0)
);

-- escalado_jugadores: Factores de escalado según el número de jugadores en la partida.
CREATE TABLE escalado_jugadores (
  num_jugadores SMALLINT NOT NULL,
  factor_cantidad NUMERIC(4,2) NOT NULL,
  factor_vida NUMERIC(4,2) NOT NULL,
  factor_xp NUMERIC(4,2) NOT NULL,
  PRIMARY KEY (num_jugadores),
  CHECK (num_jugadores BETWEEN 1 AND 4)
);

-- parametro_juego: Parámetros generales ajustables desde el panel de administración.
CREATE TABLE parametro_juego (
  clave VARCHAR(40) NOT NULL,
  valor VARCHAR(40) NOT NULL,
  descripcion VARCHAR(200),
  PRIMARY KEY (clave)
);

-- usuario: Cuentas de jugadores y administradores con su progreso general.
CREATE TABLE usuario (
  id_usuario INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  nombre_usuario VARCHAR(30) NOT NULL UNIQUE,
  correo VARCHAR(100) NOT NULL UNIQUE,
  contrasena_hash CHAR(60) NOT NULL,
  rol VARCHAR(15) NOT NULL DEFAULT 'jugador',
  nombre_visible VARCHAR(30) NOT NULL,
  color_avatar CHAR(7),
  nivel_cuenta SMALLINT NOT NULL DEFAULT 1,
  xp_cuenta INT NOT NULL DEFAULT 0,
  oro INT NOT NULL DEFAULT 0,
  estado VARCHAR(10) NOT NULL DEFAULT 'activo',
  fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_usuario),
  CHECK (rol IN ('jugador','administrador')),
  CHECK (estado IN ('activo','inactivo')),
  CHECK (nivel_cuenta >= 1),
  CHECK (oro >= 0)
);

-- progreso_mejora: Nivel que cada usuario tiene en cada mejora permanente (relación N:M).
CREATE TABLE progreso_mejora (
  id_usuario INT NOT NULL,
  id_mejora INT NOT NULL,
  nivel SMALLINT NOT NULL DEFAULT 0,
  PRIMARY KEY (id_usuario, id_mejora),
  CONSTRAINT fk_progreso_mejora_id_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  CONSTRAINT fk_progreso_mejora_id_mejora FOREIGN KEY (id_mejora) REFERENCES mejora_permanente(id_mejora) ON DELETE RESTRICT,
  CHECK (nivel >= 0)
);

-- progreso_mapa: Avance de cada usuario en cada mapa y modo: desbloqueo, mejor ronda y mejor tiempo (relación ternaria).
CREATE TABLE progreso_mapa (
  id_usuario INT NOT NULL,
  id_mapa INT NOT NULL,
  id_dificultad INT NOT NULL,
  completado BOOLEAN NOT NULL DEFAULT FALSE,
  mejor_ronda SMALLINT NOT NULL DEFAULT 0,
  mejor_tiempo_seg INT,
  PRIMARY KEY (id_usuario, id_mapa, id_dificultad),
  CONSTRAINT fk_progreso_mapa_id_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  CONSTRAINT fk_progreso_mapa_id_mapa FOREIGN KEY (id_mapa) REFERENCES mapa(id_mapa) ON DELETE RESTRICT,
  CONSTRAINT fk_progreso_mapa_id_dificultad FOREIGN KEY (id_dificultad) REFERENCES dificultad(id_dificultad) ON DELETE RESTRICT
);

-- partida: Cada partida jugada.
CREATE TABLE partida (
  id_partida INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  codigo_sala CHAR(6) NOT NULL,
  id_mapa INT NOT NULL,
  id_dificultad INT NOT NULL,
  num_jugadores SMALLINT NOT NULL,
  fecha_inicio TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_fin TIMESTAMP,
  ronda_alcanzada SMALLINT NOT NULL DEFAULT 0,
  resultado VARCHAR(12) NOT NULL DEFAULT 'en_curso',
  PRIMARY KEY (id_partida),
  CONSTRAINT fk_partida_id_mapa FOREIGN KEY (id_mapa) REFERENCES mapa(id_mapa) ON DELETE RESTRICT,
  CONSTRAINT fk_partida_id_dificultad FOREIGN KEY (id_dificultad) REFERENCES dificultad(id_dificultad) ON DELETE RESTRICT,
  CHECK (resultado IN ('en_curso','victoria','derrota','abandonada')),
  CHECK (num_jugadores BETWEEN 1 AND 4)
);

-- participacion: Participación de un usuario en una partida y sus estadísticas (relación N:M usuario-partida).
CREATE TABLE participacion (
  id_participacion INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  id_partida INT NOT NULL,
  id_usuario INT NOT NULL,
  id_personaje INT NOT NULL,
  es_anfitrion BOOLEAN NOT NULL DEFAULT FALSE,
  nivel_final SMALLINT NOT NULL DEFAULT 1,
  enemigos_eliminados INT NOT NULL DEFAULT 0,
  dano_recibido INT NOT NULL DEFAULT 0,
  companeros_revividos SMALLINT NOT NULL DEFAULT 0,
  oro_ganado INT NOT NULL DEFAULT 0,
  xp_cuenta_ganada INT NOT NULL DEFAULT 0,
  PRIMARY KEY (id_participacion),
  CONSTRAINT fk_participacion_id_partida FOREIGN KEY (id_partida) REFERENCES partida(id_partida) ON DELETE CASCADE,
  CONSTRAINT fk_participacion_id_usuario FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  CONSTRAINT fk_participacion_id_personaje FOREIGN KEY (id_personaje) REFERENCES personaje(id_personaje) ON DELETE RESTRICT,
  UNIQUE (id_partida, id_usuario)
);

-- ronda: Rondas jugadas en cada partida.
CREATE TABLE ronda (
  id_ronda INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  id_partida INT NOT NULL,
  numero SMALLINT NOT NULL,
  tipo VARCHAR(10) NOT NULL,
  id_evento INT,
  enemigos_eliminados INT NOT NULL DEFAULT 0,
  objetivo_cumplido BOOLEAN,
  PRIMARY KEY (id_ronda),
  CONSTRAINT fk_ronda_id_partida FOREIGN KEY (id_partida) REFERENCES partida(id_partida) ON DELETE CASCADE,
  CONSTRAINT fk_ronda_id_evento FOREIGN KEY (id_evento) REFERENCES evento_especial(id_evento) ON DELETE RESTRICT,
  CHECK (tipo IN ('normal','jefe','evento','jefe_final')),
  UNIQUE (id_partida, numero)
);

-- eleccion_nivel: Armas o pasivas que cada jugador eligió al subir de nivel.
CREATE TABLE eleccion_nivel (
  id_eleccion INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  id_participacion INT NOT NULL,
  id_ronda INT NOT NULL,
  id_arma INT,
  id_pasiva INT,
  nivel_jugador SMALLINT NOT NULL,
  asignada_azar BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (id_eleccion),
  CONSTRAINT fk_eleccion_nivel_id_participacion FOREIGN KEY (id_participacion) REFERENCES participacion(id_participacion) ON DELETE CASCADE,
  CONSTRAINT fk_eleccion_nivel_id_ronda FOREIGN KEY (id_ronda) REFERENCES ronda(id_ronda) ON DELETE CASCADE,
  CONSTRAINT fk_eleccion_nivel_id_arma FOREIGN KEY (id_arma) REFERENCES arma(id_arma) ON DELETE RESTRICT,
  CONSTRAINT fk_eleccion_nivel_id_pasiva FOREIGN KEY (id_pasiva) REFERENCES pasiva(id_pasiva) ON DELETE RESTRICT,
  CHECK ((id_arma IS NULL) <> (id_pasiva IS NULL))
);

-- estadistica_arma: Daño causado y eliminaciones de cada arma de cada jugador en una partida.
CREATE TABLE estadistica_arma (
  id_participacion INT NOT NULL,
  id_arma INT NOT NULL,
  nivel_final SMALLINT NOT NULL DEFAULT 1,
  dano_causado BIGINT NOT NULL DEFAULT 0,
  eliminaciones INT NOT NULL DEFAULT 0,
  PRIMARY KEY (id_participacion, id_arma),
  CONSTRAINT fk_estadistica_arma_id_participacion FOREIGN KEY (id_participacion) REFERENCES participacion(id_participacion) ON DELETE CASCADE,
  CONSTRAINT fk_estadistica_arma_id_arma FOREIGN KEY (id_arma) REFERENCES arma(id_arma) ON DELETE RESTRICT
);

