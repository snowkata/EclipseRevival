-- Vista de la tabla de clasificación por mapa y modo (RF36):
-- primero las victorias por menor tiempo, después las derrotas por ronda alcanzada.
CREATE VIEW v_clasificacion AS
SELECT p.id_partida, m.nombre AS mapa, d.nombre AS modo, p.resultado, p.ronda_alcanzada, p.num_jugadores,
       EXTRACT(EPOCH FROM (p.fecha_fin - p.fecha_inicio))::INT AS duracion_seg,
       string_agg(u.nombre_visible, ', ' ORDER BY u.nombre_visible) AS equipo,
       RANK() OVER (PARTITION BY p.id_mapa, p.id_dificultad
                    ORDER BY (p.resultado = 'victoria') DESC, p.ronda_alcanzada DESC,
                             (p.fecha_fin - p.fecha_inicio) ASC) AS posicion
FROM partida p
JOIN mapa m ON m.id_mapa = p.id_mapa
JOIN dificultad d ON d.id_dificultad = p.id_dificultad
JOIN participacion pa ON pa.id_partida = p.id_partida
JOIN usuario u ON u.id_usuario = pa.id_usuario
WHERE p.resultado IN ('victoria','derrota')
GROUP BY p.id_partida, m.nombre, d.nombre;

